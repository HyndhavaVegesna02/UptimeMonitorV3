def test_check_mutate_turns_test_red_and_restores(tmp_path):
    repo = _init_repo(tmp_path)
    patch_path = _make_patch(repo, tmp_path, "VALUE = 2\n", "breaking.patch")

    turned_red, message = evidence_check.check_mutate(
        patch_path, ["test_target.py"], repo_root=repo
    )

    assert turned_red is True
    assert "test_value" in message

    # Scoped to the mutated target (AC4's own correction) -- not a whole-tree
    # `git status`, which would also flag the __pycache__/ the pytest run
    # itself creates, unrelated to whether the mutation was restored.
    assert _git(["diff", "--", "target.py"], repo).stdout == ""


