# --- AC3 + AC6: two-sided --import-provenance-module wrap ------------------


def test_check_two_sided_import_provenance_fails_when_same_root_resolves_both_times(
    tmp_path,
):
    """Reproduces the exact sprint-63 STORY-180 trap `import_provenance.py`
    itself documents: a module that resolves under the SAME root on both
    sides is an IDENTICAL, failed proof."""
    root = tmp_path / "root"
    root.mkdir()
    (root / "_evidence_check_probe_a.py").write_text("MARKER = 1\n", encoding="utf-8")

    sys.path.insert(0, str(root))
    try:
        differ, message = evidence_check.check_two_sided_import_provenance(
            "_evidence_check_probe_a", root, root
        )
        assert differ is False
        assert "IDENTICAL" in message
    finally:
        sys.path.remove(str(root))
        sys.modules.pop("_evidence_check_probe_a", None)


def test_check_two_sided_import_provenance_passes_when_roots_genuinely_differ(
    tmp_path,
):
    root = tmp_path / "root"
    root.mkdir()
    (root / "_evidence_check_probe_b.py").write_text("MARKER = 1\n", encoding="utf-8")
    other_root = tmp_path / "other_root"
    other_root.mkdir()

    sys.path.insert(0, str(root))
    try:
        differ, message = evidence_check.check_two_sided_import_provenance(
            "_evidence_check_probe_b", root, other_root
        )
        assert differ is True
        assert "DIFFER" in message
    finally:
        sys.path.remove(str(root))
        sys.modules.pop("_evidence_check_probe_b", None)


def test_check_two_sided_import_provenance_wraps_assert_import_root_not_reimplemented(
    tmp_path, monkeypatch
):
    """AC6: `check_two_sided_import_provenance` must call through to
    `assert_import_root` -- proven by making the wrapped call itself raise
    a distinctive error and observing it surface as the recorded outcome,
    rather than any independently-reimplemented resolution logic."""

    def fake_assert_import_root(module_name, expected_root):
        # Deliberately ignores expected_root, so both sides raise the
        # IDENTICAL fake error -- proving the wrapper's outcome comes from
        # whatever assert_import_root does, not from an independent
        # left-vs-right resolution this module invented itself.
        raise WrongImportRootError(f"FAKE for {module_name}")

    monkeypatch.setattr(evidence_check, "assert_import_root", fake_assert_import_root)

    differ, message = evidence_check.check_two_sided_import_provenance(
        "whatever", tmp_path / "a", tmp_path / "b"
    )
    assert differ is False
    assert "FAKE for whatever" in message


